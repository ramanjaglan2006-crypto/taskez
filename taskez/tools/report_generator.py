from typing import Any, Dict, List
from taskez.tools.base import BaseTool

class ReportGeneratorTool(BaseTool):
    name = "report_generator"
    description = "Synthesizes gathered multi-step data into a clean, structured JSON or Markdown final report."

    def _run(self, title: str, goal: str, key_sections: List[Dict[str, Any]], format_type: str = "markdown") -> Dict[str, Any]:
        if not title or not goal:
            raise ValueError("Title and Goal are required for report synthesis.")
            
        format_clean = format_type.lower().strip()
        
        md_lines = [
            f"# {title}",
            f"**Goal:** {goal}",
            f"**Generated by:** TaskEZ Autonomous Agent Engine",
            "---",
            "## Executive Summary",
            f"This structured report synthesizes multi-step research and automated tool findings for the requested goal: *{goal}*.\n"
        ]
        
        for section in key_sections:
            sec_title = section.get("heading", "Section")
            sec_content = section.get("content", "")
            md_lines.append(f"### {sec_title}")
            md_lines.append(f"{sec_content}\n")
            
            if "bullets" in section and section["bullets"]:
                for item in section["bullets"]:
                    md_lines.append(f"- {item}")
                md_lines.append("")

        md_lines.append("---")
        md_lines.append("*Report complete. Output verified by TaskEZ Agent Engine.*")
        
        formatted_md = "\n".join(md_lines)
        
        return {
            "title": title,
            "goal": goal,
            "format": format_clean,
            "markdown_report": formatted_md,
            "structured_sections_count": len(key_sections)
        }
